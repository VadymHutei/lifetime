def translate(key: str, locale: str = "uk") -> str:
    pair = COPY.get(key)
    return pair[1 if locale == "en" else 0] if pair else key


def format_number(value, locale: str = "uk", decimals: int = 1) -> str:
    if value is None:
        return "—"
    text = f"{value:,.{decimals}f}"
    return text.replace(",", "\u00a0").replace(".", ",") if locale == "uk" else text


def format_duration(value: int, unit: str, locale: str = "uk") -> str:
    """Inflect calendar units; 11–14 take the plural form in Ukrainian."""
    forms = {
        "years": ("рік", "роки", "років"),
        "months": ("місяць", "місяці", "місяців"),
        "days": ("день", "дні", "днів"),
    }
    if locale == "en":
        word = unit[:-1] if value == 1 else unit
    else:
        index = 2 if 11 <= value % 100 <= 14 else (0 if value % 10 == 1 else 1 if 2 <= value % 10 <= 4 else 2)
        word = forms[unit][index]
    return f"{value} {word}"
